// ======================================================================
// 购物车工具文件 —— 封装 localStorage 的存取操作
// ----------------------------------------------------------------------
// 为什么单独写一个文件？
//   1. localStorage 的 API 比较原始（setItem/getItem/removeItem），
//      直接操作字符串容易出错，封装成对象操作更安全
//   2. 多个页面（Detail.vue、Cart.vue、App.vue）都需要操作购物车数据，
//      统一从这里读取，保证数据一致性
//   3. 以后如果改成 Pinia/Vuex 或后端接口，只需要改这一个文件
//
// localStorage 是什么？
//   浏览器提供的本地存储空间，数据以"键值对"形式保存
//   特点：关闭浏览器再打开，数据还在（除非用户手动清除）
//   限制：只能存字符串，所以存对象时要 JSON.stringify，取时要 JSON.parse
// ======================================================================

// localStorage 里存购物车数据的 key 名（可以随便起，但项目里要统一）
const CART_KEY = 'my_shopping_cart'

// ----------------------------------------------------------------------
// 读取购物车：从 localStorage 里把购物车数组读出来
// ----------------------------------------------------------------------
// 返回值：一个数组，每个元素是一个商品对象
//   格式：[{ id: 1, title: 'xxx', price: '100', image: '...', count: 2 }, ...]
//   如果没有数据，返回空数组 []
// ----------------------------------------------------------------------
export const getCart = () => {
  // localStorage.getItem(key) 返回字符串或 null
  // 如果从来没有存过，返回 null，这时候要返回空数组
  const json = localStorage.getItem(CART_KEY)

  // JSON.parse 把字符串转回对象/数组
  // 如果 json 是 null，JSON.parse(null) 会报错，所以要先判断
  // || '[]' 的意思是：如果 json 是 null/undefined/空字符串，就当成 '[]' 来解析
  return JSON.parse(json || '[]')
}

// ----------------------------------------------------------------------
// 保存购物车：把购物车数组写进 localStorage
// ----------------------------------------------------------------------
// 参数 list：一个数组，包含所有购物车商品
// 注意：localStorage 只能存字符串，所以要 JSON.stringify 转字符串
// ----------------------------------------------------------------------
const saveCart = (list) => {
  localStorage.setItem(CART_KEY, JSON.stringify(list))
}

// ----------------------------------------------------------------------
// 添加商品到购物车
// ----------------------------------------------------------------------
// 参数 product：商品对象，包含 id, title, price, image 等字段
// 逻辑：
//   1. 先读取现有购物车
//   2. 检查商品是否已经在购物车里（根据 id 判断）
//   3. 如果已存在，数量 +1；如果不存在，新增一条，count 设为 1
//   4. 保存回 localStorage
// ----------------------------------------------------------------------
export const addToCart = (product) => {
  // 先读取现有购物车数据
  const cart = getCart()

  // find 方法：遍历数组，找到第一个满足条件的元素
  // 这里根据 id 查找，看商品是否已经在购物车里
  const existing = cart.find((item) => item.id === product.id)

  if (existing) {
    // 商品已在购物车里，数量 +1
    existing.count += 1
  } else {
    // 商品不在购物车里，新增一条
    // 用展开运算符 ...product 把商品的所有字段复制过来，再加一个 count: 1
    cart.push({
      ...product,   // 复制商品的 id, title, price, image 等所有字段
      count: 1,     // 新增字段：购买数量，默认 1
    })
  }

  // 保存回 localStorage
  saveCart(cart)
}

// ----------------------------------------------------------------------
// 从购物车删除商品
// ----------------------------------------------------------------------
// 参数 productId：要删除的商品 ID
// 逻辑：用 filter 把 id 不等于 productId 的商品保留下来，等于的被过滤掉
// ----------------------------------------------------------------------
export const removeFromCart = (productId) => {
  const cart = getCart()
  // filter 返回新数组，不包含被删除的那个商品
  const newCart = cart.filter((item) => item.id !== productId)
  saveCart(newCart)
}

// ----------------------------------------------------------------------
// 更新购物车中某商品的数量
// ----------------------------------------------------------------------
// 参数 productId：商品 ID
// 参数 count：新的数量（如果减到 0 或负数，就删除该商品）
// ----------------------------------------------------------------------
export const updateCartCount = (productId, count) => {
  const cart = getCart()
  const item = cart.find((item) => item.id === productId)

  if (!item) return // 商品不存在，直接返回

  if (count <= 0) {
    // 数量减到 0 或以下，从购物车删除
    removeFromCart(productId)
  } else {
    // 更新数量
    item.count = count
    saveCart(cart)
  }
}

// ----------------------------------------------------------------------
// 获取购物车商品总数（用于 Tabbar Badge 显示）
// ----------------------------------------------------------------------
// 返回值：购物车中所有商品的 count 之和
// 比如购物车里有 2 个 iPhone、1 个耳机，总数就是 3
// ----------------------------------------------------------------------
export const getCartTotalCount = () => {
  const cart = getCart()
  // reduce 方法：把数组"累积"成一个值
  // sum 是累积值（初始为 0），item 是当前遍历到的商品
  // 每次把 item.count 加到 sum 上，最后返回总和
  return cart.reduce((sum, item) => sum + item.count, 0)
}

// ----------------------------------------------------------------------
// 清空购物车（结算后或用户主动清空时调用）
// ----------------------------------------------------------------------
export const clearCart = () => {
  localStorage.removeItem(CART_KEY)
}
